-- 1. Create user applications table linked to Supabase Auth
create table if not exists public.user_applications (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete cascade not null default auth.uid(),
    conference_id text not null,
    status text not null default 'Interested' check (status in (
        'Interested',
        'Shortlisted',
        'Preparing',
        'Submitted',
        'Under Review',
        'Accepted',
        'Rejected',
        'Withdrawn'
    )),
    notes text,
    added_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    submitted_at date,
    decision_at date,
    constraint unique_user_conference unique (user_id, conference_id)
);

-- Index for high-performance lookup per user
create index if not exists idx_user_applications_user_id 
    on public.user_applications(user_id);

create index if not exists idx_user_applications_status 
    on public.user_applications(user_id, status);

-- Auto-update updated_at timestamp on record updates
create or replace function public.handle_updated_at()
returns trigger as $$
begin
    new.updated_at = now();
    return new;
end;
$$ language plpgsql;

drop trigger if exists set_updated_at on public.user_applications;
create trigger set_updated_at
    before update on public.user_applications
    for each row
    execute function public.handle_updated_at();

-- =============================================================================
-- 2. Configure Row Level Security (RLS) - Absolute User Data Isolation
-- =============================================================================

alter table public.user_applications enable row level security;

-- Policy 1: Users can only view their own tracked applications
drop policy if exists "Users can view own tracking records" on public.user_applications;
create policy "Users can view own tracking records"
    on public.user_applications for select
    using (auth.uid() = user_id);

-- Policy 2: Users can only insert records belonging to their own user_id
drop policy if exists "Users can create own tracking records" on public.user_applications;
create policy "Users can create own tracking records"
    on public.user_applications for insert
    with check (auth.uid() = user_id);

-- Policy 3: Users can only modify their own tracking records
drop policy if exists "Users can update own tracking records" on public.user_applications;
create policy "Users can update own tracking records"
    on public.user_applications for update
    using (auth.uid() = user_id);

-- Policy 4: Users can only delete their own tracking records
drop policy if exists "Users can delete own tracking records" on public.user_applications;
create policy "Users can delete own tracking records"
    on public.user_applications for delete
    using (auth.uid() = user_id);

